/* Capture the real local app in a fresh browser, never a personal browser profile. */
const path = require('path');
const fs = require('fs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.EDGE_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const context = await browser.newContext({viewport:{width:1440,height:1050}, deviceScaleFactor:1, reducedMotion:'reduce'});
  const page = await context.newPage();
  const url = process.env.FOCUS_URL || 'http://127.0.0.1:8650';
  const out = path.resolve('docs/media'); fs.mkdirSync(out,{recursive:true});
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  await page.goto(url);
  await page.waitForTimeout(2500);
  await page.screenshot({path:path.join(out,'initial-check.png'),fullPage:true});
  await page.getByRole('button',{name:/Explore sample workspace/}).click();
  await page.getByRole('heading',{name:'Make room for what matters, Zubair.'}).waitFor();
  await page.waitForTimeout(900);
  if(process.env.FOCUS_MOBILE_ONLY) {
    await page.getByRole('link',{name:'Projects & board',exact:false}).click();
    await page.getByRole('heading',{name:'From idea to done.'}).waitFor();
    await page.setViewportSize({width:390,height:844});
    await page.waitForTimeout(500);
    await page.locator('[data-testid="stMain"]').evaluate(el=>el.scrollTop=0);
    await page.screenshot({path:path.join(out,'mobile-board.png'),fullPage:true});
    await browser.close();
    console.log('Refreshed clean mobile screenshot');
    return;
  }
  await page.keyboard.press('Control+k');
  await page.getByRole('textbox',{name:'Search tasks and notes',exact:true}).fill('networking');
  await page.getByRole('textbox',{name:'Search tasks and notes',exact:true}).press('Enter');
  await page.getByRole('button',{name:/Study networking fundamentals/}).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('textbox',{name:'Search tasks and notes',exact:true}).waitFor({state:'hidden'});
  await page.screenshot({path:path.join(out,'today.png'),fullPage:true});
  async function visit(label, heading, filename) {
    await page.getByRole('link',{name:label,exact:false}).click();
    await page.getByRole('heading',{name:heading,exact:true}).waitFor();
    await page.waitForTimeout(500);
    await page.locator('[data-testid="stMain"]').evaluate(el=>el.scrollTop=0);
    await page.screenshot({path:path.join(out,filename),fullPage:true});
    const exceptions = await page.locator('[data-testid="stException"]').count();
    if(exceptions) throw new Error('Streamlit exception on '+label);
  }
  await visit('Projects & board','From idea to done.','board.png');
  const dragged = page.locator('article.task').filter({has:page.getByText('Refine the landing page',{exact:true})});
  await dragged.waitFor();
  await dragged.dragTo(page.locator('section.lane[data-status="Next"]'));
  await page.locator('section.lane[data-status="Next"] article').filter({has:page.getByText('Refine the landing page',{exact:true})}).waitFor();
  await page.getByRole('combobox',{name:'Move Refine the landing page',exact:true}).selectOption('Doing');
  await page.locator('section.lane[data-status="Doing"] article').filter({has:page.getByText('Refine the landing page',{exact:true})}).waitFor();
  await page.screenshot({path:path.join(out,'board.png'),fullPage:true});
  await visit('Notes','A place to think clearly.','notes.png');
  await page.getByRole('button',{name:/New note/}).click();
  const testTitle='Autosave verification '+Date.now();
  const noteTitle=page.getByRole('textbox',{name:'Note title',exact:true});
  for(let attempt=0;attempt<40 && await noteTitle.inputValue()!=='';attempt++) await page.waitForTimeout(100);
  if(await noteTitle.inputValue()!=='') throw new Error('New note did not clear the title');
  await noteTitle.fill(testTitle);
  await page.getByRole('textbox',{name:'Note title',exact:true}).press('Enter');
  const editor=page.getByRole('textbox',{name:'Markdown',exact:true});
  await editor.fill('# Draft recovery\n\nThis typed text must survive a fresh session.');
  await page.waitForTimeout(1600);
  await page.evaluate(()=>localStorage.clear());
  await page.reload();
  await page.getByRole('button',{name:/Explore sample workspace/}).click();
  await page.getByRole('button',{name:/Leave demo/}).waitFor();
  await page.waitForTimeout(300);
  await page.getByText('Recover drafts',{exact:true}).click();
  await page.getByRole('button',{name:testTitle,exact:true}).click();
  for(let attempt=0;attempt<40 && !(await editor.inputValue()).includes('This typed text must survive');attempt++) await page.waitForTimeout(100);
  if(!(await editor.inputValue()).includes('This typed text must survive')) throw new Error('Autosave did not persist to the database');
  await page.getByRole('button',{name:/Save note/}).click();
  await page.getByRole('button',{name:/Move note to trash/}).click();
  await page.getByRole('button',{name:/A calmer product experience/}).click();
  for(let attempt=0;attempt<40 && await noteTitle.inputValue()!=='A calmer product experience';attempt++) await page.waitForTimeout(100);
  await page.screenshot({path:path.join(out,'notes.png'),fullPage:true});
  await page.getByRole('tab',{name:'Preview',exact:true}).click();
  await page.waitForTimeout(200);
  await page.screenshot({path:path.join(out,'note-preview.png'),fullPage:true});
  await visit('Focus room','One thing. Your full attention.','focus-setup.png');
  const existing = page.getByRole('button',{name:/Resume/});
  if(await existing.count()) {
    await existing.click();
  } else {
    await page.getByRole('textbox',{name:'Session intention',exact:true}).fill('Refine the landing page');
    await page.getByRole('button',{name:/Start focusing/}).click();
  }
  await page.getByRole('button',{name:/Pause/}).waitFor();
  await page.waitForTimeout(1300);
  await page.screenshot({path:path.join(out,'focus.png'),fullPage:true});
  await page.getByRole('button',{name:/Pause/}).click();
  await page.getByRole('button',{name:/Resume/}).waitFor();
  await visit('Activity & review','Notice the work you have done.','review.png');
  await visit('Planning & templates','Make the week workable.','planning.png');
  await page.getByRole('tab',{name:'Project templates',exact:true}).click();
  await page.waitForTimeout(150);
  await page.screenshot({path:path.join(out,'templates.png'),fullPage:true});
  await visit('Settings & backup','Make it feel like yours.','settings.png');
  await page.getByRole('tab',{name:'Export & backup',exact:true}).click();
  await page.waitForTimeout(200);
  await page.screenshot({path:path.join(out,'backup.png'),fullPage:true});
  await page.getByText('Password-encrypted backup',{exact:true}).click();
  await page.getByRole('textbox',{name:'Backup password · at least 12 characters',exact:true}).fill('A browser test passphrase');
  await page.getByRole('textbox',{name:'Confirm backup password',exact:true}).fill('A browser test passphrase');
  await page.getByRole('button',{name:'Create encrypted backup',exact:true}).click();
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download encrypted backup',exact:true}).click();
  const encryptedDownload=await downloadEvent;
  fs.mkdirSync(path.resolve('test-data/browser'),{recursive:true});
  const encryptedPath=path.resolve('test-data/browser/backup.focus');
  await encryptedDownload.saveAs(encryptedPath);
  await page.locator('input[type="file"]').setInputFiles(encryptedPath);
  const restorePassword=page.getByRole('textbox',{name:'Restore password',exact:true});
  await restorePassword.fill('A wrong browser passphrase'); await restorePassword.press('Enter');
  await page.getByText('Incorrect password or damaged encrypted backup. Nothing was restored.',{exact:true}).waitFor();
  await restorePassword.fill('A browser test passphrase'); await restorePassword.press('Enter');
  await page.getByRole('checkbox',{name:/Replace this workspace/}).waitFor();
  await page.screenshot({path:path.join(out,'restore-preview.png'),fullPage:true});
  await page.getByRole('tab',{name:'Appearance & routine',exact:true}).click();
  const compact = page.getByRole('switch',{name:'Compact spacing',exact:true});
  if(!await compact.isChecked()) {
    await compact.focus();
    await compact.press('Space');
  }
  await page.getByRole('button',{name:/Save preferences/}).click();
  await page.waitForTimeout(700);
  // Check mobile overflow on the same authenticated-free local demo session.
  await page.getByRole('link',{name:'Projects & board',exact:false}).click();
  await page.getByRole('heading',{name:'From idea to done.'}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(500);
  await page.locator('[data-testid="stMain"]').evaluate(el=>el.scrollTop=0);
  const overflow = await page.evaluate(() => ({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  const banner = await page.locator('[data-testid="stAlert"]').first().boundingBox();
  const header = await page.locator('[data-testid="stHeader"]').boundingBox();
  if(banner && header && banner.y < header.y+header.height) throw new Error('Mobile banner overlaps the header');
  await page.screenshot({path:path.join(out,'mobile-board.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1050});
  async function setLanguage(currentLabel,saveLabel,language){
    await page.getByRole('combobox',{name:currentLabel,exact:true}).click();
    await page.getByRole('option',{name:language,exact:true}).click();
    await page.getByRole('button',{name:new RegExp(saveLabel)}).click();
  }
  await page.getByRole('link',{name:'Settings & backup',exact:false}).click();
  await setLanguage('Interface language','Save preferences','Dari');
  await page.getByRole('link',{name:'پروژه‌ها و تختهٔ کار',exact:false}).click();
  await page.getByRole('heading',{name:'از فکر تا انجام.',exact:true}).waitFor();
  await page.screenshot({path:path.join(out,'dari-board.png'),fullPage:true});
  await page.getByRole('link',{name:'تنظیمات و نسخهٔ پشتیبان',exact:false}).click();
  await setLanguage('زبان برنامه','ذخیرهٔ تنظیمات','Pashto');
  await page.getByRole('link',{name:'پروژې او کاري تخته',exact:false}).click();
  await page.getByRole('heading',{name:'له نظره تر بشپړېدو.',exact:true}).waitFor();
  await page.screenshot({path:path.join(out,'pashto-board.png'),fullPage:true});
  fs.writeFileSync(path.join(out,'visual-check.json'),JSON.stringify({errors,overflow,quickFindShortcut:true,dragAndDrop:true,noteDraftRecovery:true,encryptedRestorePreview:true,languages:['English','Dari','Pashto'],mobileCompactHeaderClear:true,source:'Real app; separate labelled sample workspace'},null,2));
  console.log(JSON.stringify({errors,overflow,screenshots:fs.readdirSync(out).filter(n=>n.endsWith('.png'))}));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
